"""ADR-076 bit-preserving pg_node_tree octets; never a function-body normalizer."""

from psycopg import sql

DATUM_PATTERN = r"(:constvalue [0-9]+ \[ )([0-9 -]*)(\])"
DATUM_CODEC = "unsigned-octets-v1"


def datum_sql(expression: sql.Composable) -> str:
    """Only the catalog compiler supplies a closed field; values remain in SQL.

    Keep the declared byte length and tree fragments. Signed/unsigned decimal
    octets represent identical eight-bit values. An invalid octet emits a forbidden
    marker and cannot match a baseline generated by PostgreSQL's real serializer.
    """
    return (
        sql.SQL("""
      (SELECT string_agg(_dp.fragment||COALESCE(_dm.canonical,''),'' ORDER BY _dp.ordinality)
       FROM pg_catalog.regexp_split_to_table(CAST({field} AS text),:datum_pattern)
         WITH ORDINALITY AS _dp(fragment,ordinality)
       LEFT JOIN LATERAL (
         SELECT _dx.ordinality,(_dx.parts)[1]||COALESCE((
           SELECT string_agg(CASE WHEN _db.value::integer BETWEEN -128 AND 255
             THEN ((_db.value::integer+256)%256)::text||' '
             ELSE 'INVALID_OCTET ' END,'' ORDER BY _db.ordinality)
           FROM pg_catalog.regexp_split_to_table(pg_catalog.btrim((_dx.parts)[2]),' +')
             WITH ORDINALITY AS _db(value,ordinality) WHERE _db.value<>''
         ),'')||(_dx.parts)[3] AS canonical
         FROM pg_catalog.regexp_matches(CAST({field} AS text),:datum_pattern,'g')
           WITH ORDINALITY AS _dx(parts,ordinality)
       ) _dm ON _dm.ordinality=_dp.ordinality)
    """)
        .format(field=expression)
        .as_string()
    )
